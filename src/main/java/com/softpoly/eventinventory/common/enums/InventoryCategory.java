package com.softpoly.eventinventory.common.enums;

/** Broad grouping for a physical inventory item, used for filtering the catalogue. */
public enum InventoryCategory {
    FURNITURE,      // chairs, tables, stages, barricades
    AUDIO_VISUAL,   // speakers, mixers, microphones, projectors
    LIGHTING,       // par cans, trusses, controllers
    DECOR,          // drapes, flowers, signage
    CATERING,       // crockery, chafing dishes, counters
    OTHER
}
